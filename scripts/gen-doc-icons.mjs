/**
 * Generates src/styles/doc-icons.css from the real lucide sources.
 *
 * Starlight's sidebar has no per-item icon support, and its own icon set is not
 * lucide — so matching the landing page means bringing lucide in ourselves.
 * Rather than reimplementing Starlight's sidebar component, each item carries a
 * `data-icon` attribute and this stylesheet paints it with a CSS mask, so the
 * glyph inherits `currentColor` and themes with everything else.
 *
 * The mask data comes from lucide-static, not from hand-copied path data:
 * recalling path data is exactly the kind of guess that ships a broken glyph.
 *
 * The OUTPUT IS COMMITTED so a release build never needs this script or the
 * lucide-static devDependency. Re-run with:  node scripts/gen-doc-icons.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const iconsDir = path.join(here, "..", "node_modules", "lucide-static", "icons");
const out = path.join(here, "..", "src", "styles", "doc-icons.css");

// Keys are the data-icon values used in astro.config.mjs and page frontmatter.
// Values are lucide icon names. The first six MUST match the landing page's
// feature icons — that is the whole point of the exercise.
const ICONS = {
  // Concepts — mirrored from the landing page
  workspaces: "layers",
  knowledge: "book-text",
  agents: "bot",
  skills: "puzzle",
  chat: "messages-square",
  secrets: "key-round",
  connections: "plug",
  notifications: "bell",
  scheduling: "calendar-clock",
  models: "cpu",
  backup: "archive",
  // Getting started
  overview: "compass",
  start: "rocket",
  // Installation
  linux: "server",
  docker: "container",
  macos: "laptop",
  windows: "app-window",
  binary: "download",
  // Operations
  config: "sliders-horizontal",
  health: "activity",
  // Reference
  cli: "terminal",
  services: "layout-grid",
};

const missing = Object.values(ICONS).filter(
  (n) => !existsSync(path.join(iconsDir, `${n}.svg`)),
);
if (missing.length) {
  console.error("lucide icons not found:", missing.join(", "));
  process.exit(1);
}

const rules = Object.entries(ICONS)
  .map(([key, name]) => {
    const svg = readFileSync(path.join(iconsDir, `${name}.svg`), "utf8")
      .replace(/\n\s*/g, " ")
      .trim();
    // A mask needs the glyph as a data URI. Encode only what must be encoded so
    // the file stays readable and diffable.
    const uri = encodeURIComponent(svg)
      .replace(/'/g, "%27")
      .replace(/"/g, "%22");
    return `[data-icon="${key}"]::before { -webkit-mask-image: url("data:image/svg+xml,${uri}"); mask-image: url("data:image/svg+xml,${uri}"); }`;
  })
  .join("\n");

const css = `/* GENERATED by scripts/gen-doc-icons.mjs — do not edit by hand.
   Re-run: node scripts/gen-doc-icons.mjs
   Source: lucide-static, the same icon family the landing page uses. */

:where([data-icon])::before {
  content: "";
  display: inline-block;
  inline-size: 1em;
  block-size: 1em;
  flex: none;
  background-color: currentColor;
  -webkit-mask-repeat: no-repeat;
  mask-repeat: no-repeat;
  -webkit-mask-size: contain;
  mask-size: contain;
  -webkit-mask-position: center;
  mask-position: center;
  vertical-align: -0.135em;
}

/* Sidebar links: the icon sits inline, slightly muted until active. */
.sidebar-content a[data-icon] {
  display: flex;
  align-items: center;
  gap: 0.55em;
}
.sidebar-content a[data-icon]::before {
  opacity: 0.55;
  transition: opacity 150ms ease;
}
.sidebar-content a[data-icon]:hover::before,
.sidebar-content a[data-icon][aria-current="page"]::before {
  opacity: 1;
  color: var(--sl-color-accent);
}

${rules}
`;

writeFileSync(out, css);
console.log(`wrote ${path.relative(path.join(here, ".."), out)} — ${Object.keys(ICONS).length} icons`);
