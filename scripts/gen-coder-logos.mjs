/**
 * Writes brand marks for the coder CLIs that the vendored provider-logo set
 * does not contain.
 *
 * The provider logos come from the product repo and cover SERVICES. The coder
 * tools are a different axis: Claude Code is not Anthropic-the-provider, and
 * using anthropic.svg for it was the reason "the Coders images are wrong" —
 * a bare corporate glyph where a product mark belongs.
 *
 * Source is simple-icons, so these are the real marks rather than lookalikes,
 * drawn in each brand's own colour because the tiles are white.
 *
 * Output is COMMITTED; this script only needs re-running to add or refresh a
 * mark. Re-run with:  node scripts/gen-coder-logos.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const si = require("simple-icons");

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, "..", "src", "assets", "logos");

// filename -> simple-icons export. Only marks missing from the vendored set.
const WANTED = {
  claude: "siClaude",
  cursor: "siCursor",
};

let n = 0;
for (const [file, key] of Object.entries(WANTED)) {
  const icon = si[key];
  if (!icon) {
    console.error(`simple-icons has no ${key} — refusing to invent one`);
    process.exit(1);
  }
  const svg = `<!-- ${icon.title} — generated by scripts/gen-coder-logos.mjs from simple-icons. Do not hand-edit. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" role="img" aria-label="${icon.title}"><path fill="#${icon.hex}" d="${icon.path}"/></svg>
`;
  writeFileSync(path.join(outDir, `${file}.svg`), svg);
  console.log(`wrote ${file}.svg  (${icon.title}, #${icon.hex})`);
  n++;
}
console.log(`${n} coder marks written`);
